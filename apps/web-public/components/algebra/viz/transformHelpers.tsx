export function formatPair(p: Vec2, digits = 2): string {
  const f = (n: number) => {
    if (Math.abs(n) < 1e-9) return '0';
    const r = Math.round(n);
    if (Math.abs(n - r) < 1e-8) return String(r);
    return present(Number(n.toFixed(digits)));
  };
  return `(${f(p.x)}, ${f(p.y)})`;
}

export function nearZero(v: Vec2, eps = DET_EPS): boolean {
  return Math.hypot(v.x, v.y) < eps;
}

export function vecEq(a: Vec2, b: Vec2, eps = 1e-6): boolean {
  return Math.hypot(a.x - b.x, a.y - b.y) < eps;
}

export function matEq(a: Mat2, b: Mat2, eps = 1e-6): boolean {
  return (
    Math.abs(a[0][0] - b[0][0]) < eps &&
    Math.abs(a[0][1] - b[0][1]) < eps &&
    Math.abs(a[1][0] - b[1][0]) < eps &&
    Math.abs(a[1][1] - b[1][1]) < eps
  );
}

export function matLerp(A: Mat2, t: number): Mat2 {
  const s = 1 - t;
  return [
    [s + t * A[0][0], t * A[0][1]],
    [t * A[1][0], s + t * A[1][1]],
  ];
}

export function transformPts(A: Mat2, pts: Vec2[]): Vec2[] {
  return pts.map((p) => applyMat(A, p));
}

/** Cartesian grid lines transformed by M (I = original). */
export function gridLines(
  M: Mat2,
  extent = 2.5,
  count = 11,
): Array<[Vec2, Vec2]> {
  const lines: Array<[Vec2, Vec2]> = [];
  for (const t of linspace(-extent, extent, count)) {
    lines.push([applyMat(M, { x: t, y: -extent }), applyMat(M, { x: t, y: extent })]);
    lines.push([applyMat(M, { x: -extent, y: t }), applyMat(M, { x: extent, y: t })]);
  }
  return lines;
}

/** Oblique lattice generated by integer combos of b1, b2. */
export function basisGridLines(
  b1: Vec2,
  b2: Vec2,
  kMax = 3,
): Array<[Vec2, Vec2]> {
  const lines: Array<[Vec2, Vec2]> = [];
  for (let k = -kMax; k <= kMax; k++) {
    const a = { x: k * b1.x - kMax * b2.x, y: k * b1.y - kMax * b2.y };
    const b = { x: k * b1.x + kMax * b2.x, y: k * b1.y + kMax * b2.y };
    lines.push([a, b]);
  }
  for (let l = -kMax; l <= kMax; l++) {
    const a = { x: -kMax * b1.x + l * b2.x, y: -kMax * b1.y + l * b2.y };
    const b = { x: kMax * b1.x + l * b2.x, y: kMax * b1.y + l * b2.y };
    lines.push([a, b]);
  }
  return lines;
}

export function polyPoints(
  pts: Vec2[],
  to: (p: Vec2) => { x: number; y: number },
): string {
  return pts.map((p) => {
    const q = to(p);
    return `${q.x},${q.y}`;
  }).join(' ');
}


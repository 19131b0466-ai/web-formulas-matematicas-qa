export function Badge({
  tone = 'neutral',
  children,
}: {
  tone?: 'ok' | 'bad' | 'warn' | 'neutral';
  children: ReactNode;
}) {
  const cls =
    tone === 'ok'
      ? 'border-emerald-600/40 bg-emerald-500/10 text-emerald-800 dark:text-emerald-300'
      : tone === 'bad'
        ? 'border-rose-600/40 bg-rose-500/10 text-rose-800 dark:text-rose-300'
        : tone === 'warn'
          ? 'border-amber-600/40 bg-amber-500/10 text-amber-900 dark:text-amber-200'
          : 'border-[var(--border)] bg-[var(--bg)] text-[var(--fg-muted)]';
  return (
    <span className={`inline-flex items-center rounded-md border px-2 py-0.5 text-xs font-medium ${cls}`}>
      {children}
    </span>
  );
}


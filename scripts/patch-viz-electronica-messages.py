def deep_copy(obj):
    return json.loads(json.dumps(obj))


def patch_leaves(src: dict, overlay: dict) -> dict:
    out = deep_copy(src)
    for k, v in overlay.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = patch_leaves(out[k], v)
        else:
            out[k] = v
    return out


